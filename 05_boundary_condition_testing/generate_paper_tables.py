print(f"\n总计 {len(all_properties)} 个属性涉及边界条件测试\n")

# 按类型列出属性
for btype in ['greater', 'less', 'less_equal', 'range']:
    props = sorted(set(q['property_id'] for q in report['query_details'].get(btype, [])))
    btype_display = {
        'greater': 'Greater than (>)',
        'less': 'Less than (<)',
        'less_equal': 'Less or equal (<=)',
        'range': 'Range (BETWEEN)'
    }
    print(f"{btype_display[btype]:20s}: {props[:10]}")
    if len(props) > 10:
        print(f"{'':20s}  + {len(props) - 10} more")
    print()

